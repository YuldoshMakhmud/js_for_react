// ternary  operator
let age = 20;
let canVote = (age >= 18) ? "Yes" : "No";
console.log(canVote); // Output: Yes         
// ternary operator is a shorthand for if-else statement. It takes three operands: a condition, a value if the condition is true, and a value if the condition is false.
    // The syntax is: condition ? value_if_true : value_if_false
    // In this example, the condition is age >= 18. If the condition is true, the value "Yes" is assigned to canVote. If the condition is false, the value "No" is assigned to canVote.