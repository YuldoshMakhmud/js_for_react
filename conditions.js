// switch case
let day = "Monday";
switch (day) {
    case "Monday":
        console.log("Bugun dushanba");
        break;
    case "Tuesday":
        console.log("Bugun seshanba");
        break;
    case "Wednesday":
        console.log("Bugun chorshanba");
        break;
    default:
        console.log("Bunday kun yoq");
}   

